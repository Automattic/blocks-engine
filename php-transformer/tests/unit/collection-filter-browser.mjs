import { readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const playwright = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { chromium } = playwright.chromium ? playwright : playwright.default;
import assert from 'node:assert/strict';

const artifactDir = process.env.COLLECTION_FILTER_ARTIFACT_DIR || tmpdir();
const artifact = (name) => join(artifactDir, name);
const result = JSON.parse(readFileSync(artifact('collection-filter-result.json')));
const view = readFileSync(artifact('collection-filter-view.mjs'), 'utf8');
const runtime = view.replace(/^import .*;$/m, '').replace('export function refresh', 'function refresh').replace(/store\([\s\S]*$/, '') + '\nwindow.refreshCollection=refresh;';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
await page.setContent(result.serialized_blocks);
assert.equal(await page.locator('input').getAttribute('type'), 'text', 'native field retains the omitted source text input type');
await page.addScriptTag({ content: runtime });
const states = await page.evaluate(() => {
    const root = document.querySelector('[data-wp-interactive]');
    const context = JSON.parse(root.dataset.wpContext);
    const visible = () => context.items.map((item) => root.querySelector('.' + item.marker)).map((node, index) => node && !node.hidden ? index : null).filter((index) => index !== null);
    const run = (query, category) => { context.query = query; context.category = category; window.refreshCollection(root, context); return { visible: visible(), empty: !root.querySelector('[data-wp-bind--hidden$="::state.hasMatches"]').hidden }; };
    const results = [run('', 0), run('ORCHID', 0), run('violet', 1), run('orchid', 1), run('not-present', 0)];
    root.querySelector('.wp-block-accordion-item p').textContent = 'Owner edited answer magnolia.';
    results.push(run('magnolia', 0), run('orchid', 0));
    return results;
});
assert.deepEqual(states, [{ visible: [0, 1], empty: false }, { visible: [0], empty: false }, { visible: [], empty: true }, { visible: [0], empty: false }, { visible: [], empty: true }, { visible: [0], empty: false }, { visible: [], empty: true }]);
await page.addStyleTag({ content: '.wp-block-accordion-heading__toggle-icon{font-size:0}' });
const semanticStates = await page.evaluate(() => {
    const root = document.querySelector('[data-wp-interactive]');
    const context = JSON.parse(root.dataset.wpContext);
    const items = context.items.map((item) => root.querySelector('.' + item.marker));
    const run = (query) => { context.query = query; context.category = 0; window.refreshCollection(root, context); return items.map((item, index) => !item.hidden ? index : null).filter((index) => index !== null); };
    const results = [run('+')];
    const author = document.createElement('span'); author.textContent = 'C++ author symbol'; items[0].querySelector('p').append(author);
    results.push(run('+'));
    author.remove();
    const visibleDecorative = document.createElement('span'); visibleDecorative.setAttribute('aria-hidden', 'true'); visibleDecorative.style.fontSize = '16px'; visibleDecorative.textContent = '+'; items[1].querySelector('p').append(visibleDecorative);
    results.push(run('+'));
    visibleDecorative.remove();
    const decorativeAncestor = document.createElement('span'); decorativeAncestor.setAttribute('aria-hidden', 'true'); decorativeAncestor.style.fontSize = '0';
    const visibleChild = document.createElement('span'); visibleChild.style.fontSize = '16px'; visibleChild.textContent = '+'; decorativeAncestor.append(visibleChild); items[1].querySelector('p').append(decorativeAncestor);
    results.push(run('+')); decorativeAncestor.remove();
    const closedAnswer = items[0].querySelector('.wp-block-accordion-panel'); closedAnswer.hidden = true; closedAnswer.setAttribute('aria-hidden', 'true'); closedAnswer.style.fontSize = '16px';
    results.push(run('magnolia'));
    const zeroFontAuthor = document.createElement('span'); zeroFontAuthor.style.fontSize = '0'; zeroFontAuthor.textContent = 'ZeroFontAuthorWord'; items[1].querySelector('.wp-block-accordion-heading').append(zeroFontAuthor);
    results.push(run('ZeroFontAuthorWord'));
    return results;
});
assert.deepEqual(semanticStates, [[], [0], [1], [1], [0], [1]], 'only zero-font aria-hidden decoration is excluded; closed answers and author symbols remain searchable');
await browser.close();
const cardBrowser = await chromium.launch({ headless: true });
const cardPage = await cardBrowser.newPage();
await cardPage.setContent(JSON.parse(readFileSync(artifact('collection-filter-cards.json'))).serialized_blocks);
await cardPage.addScriptTag({ content: runtime });
const cards = await cardPage.evaluate(() => {
    const root = document.querySelector('[data-wp-interactive]');
    const context = JSON.parse(root.dataset.wpContext);
    context.query = 'VIOLET'; context.category = 0; window.refreshCollection(root, context);
    return context.items.map((item) => root.querySelector('.' + item.marker)).filter((item) => item && !item.hidden).map((item) => item.textContent.replace(/\s+/g, ''));
});
assert.deepEqual(cards, ['SamecardAnswerviolet.']);
await cardBrowser.close();
const finite = JSON.parse(readFileSync(artifact('collection-filter-finite.json')));
const finiteBrowser = await chromium.launch({ headless: true });
const finitePage = await finiteBrowser.newPage();
await finitePage.setContent(finite.markup);
await finitePage.addScriptTag({ content: finite.view.replace(/^import .*;$/m, '').replace('export function refresh', 'function refresh').replace(/store\([\s\S]*$/, '') + '\nwindow.refreshCollection=refresh;' });
const finiteStates = await finitePage.evaluate(() => {
    const root = document.querySelector('[data-wp-interactive]');
    const context = JSON.parse(root.dataset.wpContext);
    const before = root.querySelectorAll('[class*="blocks-engine-collection-item-"]').length;
    const strip = root.querySelector('[data-wp-bind--hidden$="::state.choicesHidden"]');
    const input = root.querySelector('input');
    const status = root.querySelector('p');
    const visible = () => Array.from(root.querySelectorAll('[class*="blocks-engine-collection-item-"]')).filter((node) => !node.hidden).map((node) => context.items.findIndex((item) => node.classList.contains(item.marker)));
    const run = (query) => { context.query = query; input.value = query; window.refreshCollection(root, context); return { visible: visible(), stripHidden: strip.hidden, inputHidden: input.hidden, statusHidden: status.hidden }; };
    const searched = run('apricot');
    const cleared = run('');
    const node = root.querySelector('.' + context.items[0].marker + ' p');
    node.textContent = 'Owner added zephyranswer row';
    const edited = run('zephyranswer');
    return { before, after: root.querySelectorAll('[class*="blocks-engine-collection-item-"]').length, searched, cleared, edited, categoryOrder: context.categoryOrders[0] };
});
assert.equal(finiteStates.before, 19);
assert.equal(finiteStates.after, 19, 'global and category movement never clones items');
assert.deepEqual(finiteStates.searched.visible, [0]);
assert.equal(finiteStates.searched.stripHidden, true);
assert.equal(finiteStates.searched.inputHidden, false);
assert.equal(finiteStates.searched.statusHidden, false);
assert.equal(finiteStates.cleared.stripHidden, false);
assert.deepEqual(finiteStates.cleared.visible, [16, 12, 8, 4, 0], 'empty query restores the selected category by moving existing nodes');
assert.deepEqual(finiteStates.edited.visible, [0]);
await finiteBrowser.close();
console.log('PASS: answer-only search, case, category composition, external empty state, owner-edited live text');
